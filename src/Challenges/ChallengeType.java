package Challenges;

/**
 * Enumerates the different categories of challenges that can be encountered.
 */
public enum ChallengeType {
    /**
     * Represents a challenge involving a physical interaction, such as pulling a lever.
     */
    LEVER,

    /**
     * Represents a challenge that requires solving a riddle or answering a question.
     */
    RIDDLE,

    /**
     * Represents the absence of a challenge, allowing free passage.
     */
    NONE
}
